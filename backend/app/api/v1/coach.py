"""
Financial Coach & 1-Tap Action Execution Router
===============================================
Exposes:
- `POST /api/v1/coach/messages`: Unified Monolithic Coach (`CoachDecision` + RAG + 1-tap `ActionCard`).
- `POST /api/v1/coach/execute-action`: Deterministic execution of 1-tap Coach action buttons
  (`paypal_checkout` via PayPal Sandbox Orders v2 or `sweep_to_vault` via zero-sum double-entry).
- `GET /api/v1/coach/threads` & `GET /api/v1/coach/threads/{thread_id}/messages`: Persistent thread history.
"""

import json
from typing import Any, Dict, List
from uuid import UUID
from fastapi import APIRouter, Depends, HTTPException
from sqlmodel import select, col
from sqlmodel.ext.asyncio.session import AsyncSession

from app.database import get_session
from app.models.user import User
from app.models.bucket import Bucket
from app.models.coach import CoachThread, CoachMessage
from app.models.intent import Intent
from app.schemas.common import (
    CoachExecuteActionRequest,
    CoachExecuteActionResponse,
    CoachMessageRequest,
    CoachMessageResponse,
)
from app.api.v1.auth import get_current_user
from app.agents.insights.coach import handle_coach_query
from app.agents.rag import normalize_short_tag
from app.ledger.engine import LedgerEngine
from app.services.paypal_client import paypal_client

router = APIRouter(prefix="/coach", tags=["Financial Coach"])


@router.post("/messages", response_model=CoachMessageResponse)
async def post_coach_message(
    body: CoachMessageRequest,
    user: User = Depends(get_current_user),
    session: AsyncSession = Depends(get_session)
) -> Dict[str, Any]:
    """Send conversational query to the Unified Trinity Coach (`CoachDecision` + RAG + 1-tap ActionCard)."""
    return await handle_coach_query(
        session=session,
        user_id=user.id,
        utterance=body.utterance,
        thread_id=body.thread_id,
        chart_id=body.chart_id,
        filter_context=body.filter_context,
    )


@router.post("/execute-action", response_model=CoachExecuteActionResponse)
async def execute_coach_action(
    body: CoachExecuteActionRequest,
    user: User = Depends(get_current_user),
    session: AsyncSession = Depends(get_session)
) -> Dict[str, Any]:
    """
    Executes a pre-configured 1-tap `ActionCard` generated by the Coach after
    deterministic `LedgerEngine` verification:
    - `sweep_to_vault`: Zero-sum double-entry transfer from `bank` -> `vault`.
    - `paypal_checkout`: Places hold, creates PayPal Sandbox order, and optionally captures/settles.
    """
    short_tag = normalize_short_tag(
        body.short_tag,
        fallback_utterance=body.utterance,
        category=body.category,
        merchant_name=body.merchant_name,
    )
    balances = await LedgerEngine.get_bucket_balances(session, user.id)

    # --------------------------------------------------------------------------
    # Action 1: 1-Tap Zero-Sum Sweep to Vault (`bank` -> `vault`)
    # --------------------------------------------------------------------------
    if body.action_type == "sweep_to_vault":
        bank_info = balances.get("bank")
        vault_info = balances.get("vault")
        if not bank_info or not vault_info:
            raise HTTPException(status_code=400, detail="Trinity Bank/Vault buckets not initialized.")
        if bank_info["available"] < body.amount_cents:
            raise HTTPException(
                status_code=409,
                detail=f"Insufficient Bank Foundation balance (${bank_info['available'] / 100:.2f}) for Vault sweep.",
            )

        sweep_intent = Intent(
            user_id=user.id,
            utterance=body.utterance,
            short_tag=short_tag,
            amount=body.amount_cents,
            currency=body.currency,
            category="savings",
            necessity="daily_living",
            recommended_bucket="vault",
            source_bucket_id=bank_info["bucket_id"],
            status="settled",
        )
        session.add(sweep_intent)
        await session.commit()
        await session.refresh(sweep_intent)

        debit_leg, _ = await LedgerEngine.record_double_entry_transfer(
            session=session,
            user_id=user.id,
            from_bucket_id=bank_info["bucket_id"],
            to_bucket_id=vault_info["bucket_id"],
            amount_minor=body.amount_cents,
            entry_kind="vault_skim",
            memo=f"Coach 1-Tap Vault Sweep ({short_tag})",
            from_bucket_kind="bank",
            to_bucket_kind="vault",
        )

        return {
            "status": "settled",
            "action_type": "sweep_to_vault",
            "short_tag": short_tag,
            "amount_cents": body.amount_cents,
            "source_bucket": "bank",
            "destination_bucket": "vault",
            "intent_id": sweep_intent.id,
            "transfer_id": debit_leg.transfer_id,
            "message": f"Swept ${body.amount_cents / 100:.2f} from Bank Foundation to Locked Savings Vault.",
        }

    # --------------------------------------------------------------------------
    # Action 2: 1-Tap PayPal Sandbox Checkout (`paypal_checkout`)
    # --------------------------------------------------------------------------
    if body.action_type == "paypal_checkout":
        intent = None
        if body.intent_id:
            stmt_i = select(Intent).where(Intent.id == body.intent_id).where(Intent.user_id == user.id)
            intent = (await session.exec(stmt_i)).first()

        target_kind = body.target_bucket if body.target_bucket in ("daily", "freedom", "bills", "bank") else "freedom"
        necessity = body.necessity or ("freedom" if target_kind == "freedom" else "daily_living")

        if not intent:
            is_ok, pol_status, pol_rationale = await LedgerEngine.can_spend(
                session=session,
                user_id=user.id,
                amount_minor=body.amount_cents,
                source_kind=target_kind,
                necessity=necessity,
            )
            if not is_ok:
                raise HTTPException(status_code=409, detail=pol_rationale)

            bucket_info = balances.get(target_kind)
            intent = Intent(
                user_id=user.id,
                utterance=body.utterance,
                short_tag=short_tag,
                amount=body.amount_cents,
                currency=body.currency,
                merchant_name=body.merchant_name,
                category=body.category or "general",
                necessity=necessity,
                recommended_bucket=target_kind,
                source_bucket_id=bucket_info["bucket_id"] if bucket_info else None,
                is_emergency=body.is_emergency,
                status="allowed",
            )
            session.add(intent)
            await session.commit()
            await session.refresh(intent)
        else:
            if intent.status not in ("allowed", "override_approved"):
                raise HTTPException(
                    status_code=409,
                    detail=f"Intent is in status '{intent.status}' and requires Escape Window override before PayPal checkout.",
                )

        # Resolve hold bucket (if override_approved and target bucket < amount, draw from bank)
        hold_bucket_id = intent.source_bucket_id
        resolved_source_kind = intent.recommended_bucket or target_kind
        if intent.status == "override_approved":
            cur_avail = 0
            for k, b_info in balances.items():
                if b_info["bucket_id"] == hold_bucket_id:
                    cur_avail = b_info["available"]
                    resolved_source_kind = k
                    break
            if cur_avail < intent.amount and "bank" in balances:
                hold_bucket_id = balances["bank"]["bucket_id"]
                intent.source_bucket_id = hold_bucket_id
                resolved_source_kind = "bank"

        if not hold_bucket_id:
            stmt_b = select(Bucket).where(Bucket.user_id == user.id).where(Bucket.kind == target_kind)
            b_obj = (await session.exec(stmt_b)).first()
            if not b_obj:
                raise HTTPException(status_code=400, detail="Source bucket not found")
            hold_bucket_id = b_obj.id
            intent.source_bucket_id = hold_bucket_id

        await LedgerEngine.place_hold(
            session=session,
            user_id=user.id,
            bucket_id=hold_bucket_id,
            amount_minor=intent.amount,
            intent_id=intent.id,
            memo=f"{short_tag}: {intent.utterance[:50]}",
        )

        order_res = await paypal_client.create_order(
            intent_id=str(intent.id),
            amount_cents=intent.amount,
            description=f"{short_tag}: {intent.utterance[:50]}",
        )
        order_id = order_res.get("id") or f"ORDER-{str(intent.id)[:8]}"
        approval_url = next(
            (link["href"] for link in order_res.get("links", []) if link.get("rel") in ("approve", "payer-action")),
            f"https://www.sandbox.paypal.com/checkoutnow?token={order_id}",
        )

        intent.paypal_order_id = order_id
        intent.short_tag = intent.short_tag or short_tag

        if body.auto_capture_demo:
            cap_res = await paypal_client.capture_order(order_id=order_id, intent_id=str(intent.id))
            capture_id = f"CAPTURE-{order_id[:8]}"
            try:
                capture_id = cap_res["purchase_units"][0]["payments"]["captures"][0]["id"]
            except Exception:
                pass

            await LedgerEngine.settle_hold(session, intent.id, capture_id)
            intent.status = "settled"
            session.add(intent)
            await session.commit()

            return {
                "status": "settled",
                "action_type": "paypal_checkout",
                "short_tag": intent.short_tag,
                "amount_cents": intent.amount,
                "source_bucket": resolved_source_kind,
                "intent_id": intent.id,
                "paypal_order_id": order_id,
                "paypal_capture_id": capture_id,
                "approval_url": approval_url,
                "message": f"Paid ${intent.amount / 100:.2f} for '{intent.short_tag}' via PayPal ({resolved_source_kind.capitalize()}).",
            }

        intent.status = "executing"
        session.add(intent)
        await session.commit()
        return {
            "status": "executing",
            "action_type": "paypal_checkout",
            "short_tag": intent.short_tag,
            "amount_cents": intent.amount,
            "source_bucket": resolved_source_kind,
            "intent_id": intent.id,
            "paypal_order_id": order_id,
            "approval_url": approval_url,
            "message": f"PayPal order {order_id} created. Complete approval to settle.",
        }

    raise HTTPException(status_code=400, detail=f"Unsupported action_type '{body.action_type}'")


@router.get("/threads")
async def list_threads(
    user: User = Depends(get_current_user),
    session: AsyncSession = Depends(get_session)
) -> List[Dict[str, Any]]:
    stmt = select(CoachThread).where(CoachThread.user_id == user.id).order_by(col(CoachThread.updated_at).desc())
    res = await session.exec(stmt)
    return [t.model_dump() for t in res.all()]


@router.get("/threads/{thread_id}/messages")
async def get_thread_messages(
    thread_id: UUID,
    user: User = Depends(get_current_user),
    session: AsyncSession = Depends(get_session)
) -> List[Dict[str, Any]]:
    stmt = (
        select(CoachMessage)
        .where(CoachMessage.thread_id == thread_id)
        .order_by(col(CoachMessage.created_at).asc())
    )
    res = await session.exec(stmt)
    output: List[Dict[str, Any]] = []
    for m in res.all():
        item = m.model_dump()
        if m.action_card_json:
            try:
                item["action_card"] = json.loads(m.action_card_json)
            except Exception:
                item["action_card"] = None
        output.append(item)
    return output
