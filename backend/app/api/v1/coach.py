"""
Financial Coach & 1-Tap Action Execution Router
===============================================
Exposes:
- `POST /api/v1/coach/messages`: Unified Monolithic Coach (`CoachDecision` + RAG + 1-tap `ActionCard`).
- `POST /api/v1/coach/execute-action`: Deterministic execution of 1-tap Coach action buttons
  (`paypal_checkout` via PayPal Sandbox Orders v2 or `sweep_to_vault` via zero-sum double-entry).
- `GET /api/v1/coach/threads` & `GET /api/v1/coach/threads/{thread_id}/messages`: Persistent thread history.
"""

